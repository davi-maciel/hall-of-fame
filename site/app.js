/* Hall da Fama — table v1. Vanilla JS, no build step.
   Data: data/people.json (generated by scripts/build_people.py) + data/olympiads.json. */

const $ = (s) => document.querySelector(s);

const MEDAL = {
  gold: { label: "Ouro", rank: 4 },
  silver: { label: "Prata", rank: 3 },
  bronze: { label: "Bronze", rank: 2 },
  "honorable-mention": { label: "MH", rank: 1 },
};
const NOTE = {
  "no-award": { text: "—", label: "Sem medalha (confirmado)" },
  "inferred-no-award": { text: "—", label: "Sem medalha (inferido da contagem oficial)" },
  unknown: { text: "", label: "Medalha ainda não atribuída individualmente" },
  pending: { text: "pendente", label: "Evento ainda não realizado / resultado pendente" },
};

let DATA = null;
let OL = null;
let state = {
  view: "people", // 'people' | 'parts'
  q: "",
  ols: new Set(),
  field: "",
  scope: "",
  medal: "",
  y0: null,
  y1: null,
  sort: { key: "participations", dir: -1 },
};

const fold = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();

/* ---------- state <-> URL ---------- */
function readURL() {
  const p = new URLSearchParams(location.search);
  state.view = p.get("view") === "parts" ? "parts" : "people";
  state.q = p.get("q") || "";
  state.ols = new Set((p.get("ols") || "").split(",").filter(Boolean));
  state.field = p.get("area") || "";
  state.scope = p.get("escopo") || "";
  state.medal = p.get("medalha") || "";
  state.y0 = p.get("de") ? +p.get("de") : null;
  state.y1 = p.get("ate") ? +p.get("ate") : null;
  state.sort = state.view === "parts" ? { key: "year", dir: -1 } : { key: "participations", dir: -1 };
  const s = p.get("ord");
  if (s) {
    const [key, dir] = s.split(".");
    state.sort = { key, dir: dir === "asc" ? 1 : -1 };
  }
}
function writeURL() {
  const p = new URLSearchParams();
  if (state.view !== "people") p.set("view", state.view);
  if (state.q) p.set("q", state.q);
  if (state.ols.size) p.set("ols", [...state.ols].join(","));
  if (state.field) p.set("area", state.field);
  if (state.scope) p.set("escopo", state.scope);
  if (state.medal) p.set("medalha", state.medal);
  if (state.y0) p.set("de", state.y0);
  if (state.y1) p.set("ate", state.y1);
  const def = state.view === "people" ? "participations" : "year";
  if (!(state.sort.key === def && state.sort.dir === -1))
    p.set("ord", `${state.sort.key}.${state.sort.dir === 1 ? "asc" : "desc"}`);
  history.replaceState(null, "", p.toString() ? `?${p}` : location.pathname);
}

/* ---------- filtering ---------- */
function partMatches(part) {
  const ol = OL.olympiads[part.olympiad];
  if (state.ols.size && !state.ols.has(part.olympiad)) return false;
  if (state.field && ol.field !== state.field) return false;
  if (state.scope && ol.scope !== state.scope) return false;
  if (state.y0 && part.year < state.y0) return false;
  if (state.y1 && part.year > state.y1) return false;
  if (state.medal) {
    if (state.medal === "none") {
      if (part.medal !== null || part.medalNote === "unknown" || part.medalNote === "pending") return false;
    } else if (part.medal !== state.medal) return false;
  }
  return true;
}
function personRows() {
  const q = fold(state.q);
  return DATA.people
    .filter((p) => (!q || p.searchKey.includes(q)) && p.participations.some(partMatches))
    .map((p) => {
      const medals = { gold: 0, silver: 0, bronze: 0, "honorable-mention": 0 };
      let unknown = 0;
      for (const x of p.participations) {
        if (x.medal) medals[x.medal]++;
        else if (x.medalNote === "unknown") unknown++;
      }
      const years = p.participations.map((x) => x.year);
      return {
        p,
        name: p.name,
        participations: p.participations.length,
        distinct: new Set(p.participations.map((x) => x.olympiad)).size,
        yearMin: Math.min(...years),
        yearMax: Math.max(...years),
        gold: medals.gold, silver: medals.silver, bronze: medals.bronze,
        hm: medals["honorable-mention"], unknown,
      };
    });
}
function partRows() {
  const q = fold(state.q);
  const rows = [];
  for (const p of DATA.people) {
    if (q && !p.searchKey.includes(q)) continue;
    for (const x of p.participations)
      if (partMatches(x)) rows.push({ p, name: p.name, year: x.year, olympiad: x.olympiad, medal: x.medal, medalNote: x.medalNote });
  }
  return rows;
}

/* ---------- sorting ---------- */
const CMP = {
  name: (a, b) => a.p.searchKey.localeCompare(b.p.searchKey),
  participations: (a, b) => a.participations - b.participations || a.gold - b.gold || a.silver - b.silver,
  distinct: (a, b) => a.distinct - b.distinct || a.participations - b.participations,
  years: (a, b) => a.yearMin - b.yearMin,
  gold: (a, b) => a.gold - b.gold || a.silver - b.silver || a.bronze - b.bronze,
  silver: (a, b) => a.silver - b.silver,
  bronze: (a, b) => a.bronze - b.bronze,
  hm: (a, b) => a.hm - b.hm,
  year: (a, b) => a.year - b.year,
  olympiad: (a, b) => a.olympiad.localeCompare(b.olympiad),
  medal: (a, b) => medalRank(a) - medalRank(b),
};
const medalRank = (r) => (r.medal ? MEDAL[r.medal].rank : r.medalNote === "unknown" ? 0.5 : 0);
function sortRows(rows) {
  const { key, dir } = state.sort;
  const cmp = CMP[key] || CMP.name;
  return rows.sort((a, b) => dir * cmp(a, b) || a.p.searchKey.localeCompare(b.p.searchKey));
}

/* ---------- rendering ---------- */
const COLS = {
  people: [
    ["name", "Nome"], ["participations", "Particip.", "num"], ["distinct", "Olimp. distintas", "num"],
    ["badges", "Olimpíadas"], ["years", "Anos"],
    ["gold", "Ouro", "num"], ["silver", "Prata", "num"], ["bronze", "Bronze", "num"], ["hm", "MH", "num"],
  ],
  parts: [["year", "Ano", "num"], ["olympiad", "Olimpíada"], ["name", "Nome"], ["medal", "Resultado"]],
};
function code(olId) {
  return `<span title="${OL.olympiads[olId].name}">${OL.olympiads[olId].code}</span>`;
}
function medalCell(r) {
  if (r.medal) return MEDAL[r.medal].label === "MH" ? "Menção honrosa" : MEDAL[r.medal].label;
  const n = NOTE[r.medalNote] || NOTE["no-award"];
  return n.text ? `<span class="muted" title="${n.label}">${n.text}</span>` : "";
}
function renderHead() {
  const cols = COLS[state.view];
  $("#thead").innerHTML =
    "<tr>" +
    cols.map(([key, label, cls]) => {
      const sortable = key !== "badges";
      const arrow = state.sort.key === (key === "years" && state.view === "people" ? "years" : key)
        ? ` <span class="arrow">${state.sort.dir === 1 ? "▲" : "▼"}</span>` : "";
      return `<th class="${cls || ""}" data-key="${sortable ? key : ""}">${label}${sortable ? arrow : ""}</th>`;
    }).join("") +
    "</tr>";
}
function renderBody(rows) {
  const tb = $("#tbody");
  if (state.view === "parts") {
    tb.innerHTML = rows.map((r) =>
      `<tr class="data"><td class="num">${r.year}</td><td class="ols">${code(r.olympiad)}</td><td class="name">${r.name}</td><td>${medalCell(r)}</td></tr>`
    ).join("");
    return;
  }
  tb.innerHTML = rows.map((r) => {
    const ols = [...new Set(r.p.participations.map((x) => x.olympiad))];
    const yrs = r.yearMin === r.yearMax ? r.yearMin : `${r.yearMin}–${r.yearMax}`;
    return `<tr class="data" data-id="${r.p.id}">
      <td class="name"><a href="person.html?id=${r.p.id}">${r.name}</a></td>
      <td class="num">${r.participations}</td>
      <td class="num">${r.distinct}</td>
      <td class="ols">${ols.map(code).join(" ")}</td>
      <td>${yrs}</td>
      <td class="num">${r.gold || ""}</td><td class="num">${r.silver || ""}</td>
      <td class="num">${r.bronze || ""}</td><td class="num">${r.hm || ""}</td>
    </tr>`;
  }).join("");
}

let currentRows = [];
function render() {
  const rows = sortRows(state.view === "people" ? personRows() : partRows());
  currentRows = rows;
  renderHead();
  renderBody(rows);
  const n = rows.length;
  $("#result-line").textContent =
    state.view === "people"
      ? `${n} estudante${n === 1 ? "" : "s"} — clique em uma linha para abrir a página do estudante; clique nos cabeçalhos para ordenar`
      : `${n} participaç${n === 1 ? "ão" : "ões"}`;
  writeURL();
}

/* ---------- export ---------- */
function exportRows() {
  if (state.view === "parts")
    return {
      header: ["ano", "olimpiada", "nome", "id", "resultado", "observacao"],
      rows: currentRows.map((r) => [r.year, r.olympiad, r.name, r.p.id, r.medal || "", r.medalNote || ""]),
    };
  return {
    header: ["nome", "id", "participacoes", "olimpiadas_distintas", "olimpiadas", "primeiro_ano", "ultimo_ano", "ouro", "prata", "bronze", "mencao_honrosa", "nao_atribuidas"],
    rows: currentRows.map((r) => [
      r.name, r.p.id, r.participations, r.distinct,
      [...new Set(r.p.participations.map((x) => x.olympiad))].join("|"),
      r.yearMin, r.yearMax, r.gold, r.silver, r.bronze, r.hm, r.unknown,
    ]),
  };
}
const esc = (v) => {
  v = String(v);
  return /[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
};
function toDelim(sep) {
  const { header, rows } = exportRows();
  const line = (r) => r.map(sep === "," ? esc : String).join(sep);
  return [line(header), ...rows.map(line)].join("\n");
}
function download(name, text, type) {
  const a = document.createElement("a");
  a.href = URL.createObjectURL(new Blob([text], { type }));
  a.download = name;
  a.click();
  URL.revokeObjectURL(a.href);
}

/* ---------- wiring ---------- */
function buildControls() {
  const osel = $("#f-ol");
  if (osel.options.length === 1)
    for (const [id, o] of Object.entries(OL.olympiads)) osel.add(new Option(o.code, id));
  osel.value = [...state.ols][0] || "";
  osel.addEventListener("change", (e) => {
    state.ols = e.target.value ? new Set([e.target.value]) : new Set();
    render();
  });
  const fsel = $("#f-field");
  for (const [id, f] of Object.entries(OL.fields)) fsel.add(new Option(f.label, id));
  fsel.value = state.field;
  const ssel = $("#f-scope");
  for (const [id, label] of Object.entries(OL.scopes)) ssel.add(new Option(label, id));
  ssel.value = state.scope;
  $("#f-medal").value = state.medal;
  $("#q").value = state.q;
  $("#view-people").classList.toggle("on", state.view === "people");
  $("#view-parts").classList.toggle("on", state.view === "parts");
  if (state.y0) $("#y0").value = state.y0;
  if (state.y1) $("#y1").value = state.y1;

  $("#q").addEventListener("input", (e) => { state.q = e.target.value; render(); });
  fsel.addEventListener("change", (e) => { state.field = e.target.value; render(); });
  ssel.addEventListener("change", (e) => { state.scope = e.target.value; render(); });
  $("#f-medal").addEventListener("change", (e) => { state.medal = e.target.value; render(); });
  $("#y0").addEventListener("change", (e) => { state.y0 = e.target.value ? +e.target.value : null; render(); });
  $("#y1").addEventListener("change", (e) => { state.y1 = e.target.value ? +e.target.value : null; render(); });
  $("#clear").addEventListener("click", () => {
    Object.assign(state, { q: "", ols: new Set(), field: "", scope: "", medal: "", y0: null, y1: null });
    $("#q").value = ""; osel.value = ""; fsel.value = ""; ssel.value = ""; $("#f-medal").value = ""; $("#y0").value = ""; $("#y1").value = "";
    render();
  });
  $("#view-people").addEventListener("click", () => setView("people"));
  $("#view-parts").addEventListener("click", () => setView("parts"));
  $("#copy").addEventListener("click", async () => {
    await navigator.clipboard.writeText(toDelim("\t"));
    $("#copy").textContent = "Copiado ✓";
    setTimeout(() => ($("#copy").textContent = "Copiar TSV"), 1200);
  });
  $("#dl-csv").addEventListener("click", () => download(`hall-da-fama-${state.view}.csv`, toDelim(","), "text/csv"));
  $("#dl-json").addEventListener("click", () => {
    const { header, rows } = exportRows();
    const objs = rows.map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]])));
    download(`hall-da-fama-${state.view}.json`, JSON.stringify(objs, null, 2), "application/json");
  });
  $("#thead").addEventListener("click", (e) => {
    const th = e.target.closest("th");
    if (!th || !th.dataset.key) return;
    const key = th.dataset.key === "years" ? "years" : th.dataset.key;
    if (state.sort.key === key) state.sort.dir *= -1;
    else state.sort = { key, dir: key === "name" ? 1 : -1 };
    render();
  });
  $("#tbody").addEventListener("click", (e) => {
    if (e.target.closest("a")) return;
    const tr = e.target.closest("tr.data");
    if (!tr || state.view !== "people") return;
    location.href = `person.html?id=${tr.dataset.id}`;
  });
}
function setView(v) {
  if (state.view === v) return;
  state.view = v;
  state.sort = v === "people" ? { key: "participations", dir: -1 } : { key: "year", dir: -1 };
  $("#view-people").classList.toggle("on", v === "people");
  $("#view-parts").classList.toggle("on", v === "parts");
  render();
}

async function boot() {
  try {
    const [people, ol] = await Promise.all([
      fetch("data/people.json").then((r) => r.json()),
      fetch("data/olympiads.json").then((r) => r.json()),
    ]);
    DATA = people;
    OL = ol;
  } catch (e) {
    $("#meta-line").textContent =
      "Erro ao carregar os dados. Sirva a pasta por HTTP (ex.: python3 -m http.server na pasta site/).";
    return;
  }
  readURL();
  const m = DATA.meta;
  const nOls = Object.keys(OL.olympiads).length;
  $("#meta-line").textContent =
    `${m.peopleCount} estudantes · ${m.participationCount} participações · ${nOls} olimpíadas · dados de ${m.generatedAt.slice(0, 10)}`;
  $("#controls").hidden = false;
  buildControls();
  render();
}
boot();

let DATA = null;
let OL = null;
let state = {
  view: "people", // 'people' | 'parts'
  q: "",
  ols: new Set(), // empty = no olympiad filter (all)
  olsNone: false, // true = every olympiad deselected (shows nothing until one is ticked)
  olsAll: false, // true = AND: a person must have taken part in every selected olympiad
  field: "",
  scope: "",
  medal: "",
  y0: null,
  y1: null,
  // which participations the Pessoas statistics count: only the ones matching the filters
  // ('filtradas', default) or the person's whole record ('todas'). Filters always decide who is listed.
  stats: "filtradas",
  sort: { key: "participations", dir: -1 },
};

const fold = (s) => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();

/* Olympiads flagged `"hidden": true` in data/olympiads.json are held back from the
   site: build_people.py leaves their participations out of data/people.json and the
   UI never lists them (picker, área/escopo filters, counts). Everything else about
   the dataset — folder, checks, reports — is unchanged. */
const visibleOls = () => Object.entries(OL.olympiads).filter(([, o]) => !o.hidden);
const isVisibleOl = (id) => !!OL.olympiads[id] && !OL.olympiads[id].hidden;
const visibleValues = (key) => new Set(visibleOls().map(([, o]) => o[key]));

/* ---------- fuzzy name search ----------
   Query words may come in any order; each must match a name word (of the display name or any
   recorded spelling variant) as a prefix, or within a small edit distance (1 for 4+ letters,
   2 for 8+), so "joau silva" or "silva joao" still find "João Silva". Score: 2 per exact/prefix
   hit, 1 per fuzzy hit; 0 = no match. */
function editDistance(a, b, max) {
  if (Math.abs(a.length - b.length) > max) return max + 1;
  let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const cur = [i];
    let rowMin = i;
    for (let j = 1; j <= b.length; j++) {
      cur[j] = Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
      if (cur[j] < rowMin) rowMin = cur[j];
    }
    if (rowMin > max) return max + 1;
    prev = cur;
  }
  return prev[b.length];
}
function nameTokens(p) {
  if (!p._toks) {
    const names = [p.name, ...(p.nameVariants || [])];
    p._toks = [...new Set(names.flatMap((n) => fold(n).split(/[^a-z0-9]+/).filter(Boolean)))];
  }
  return p._toks;
}
function matchScore(p, qtoks) {
  if (!qtoks.length) return 1;
  if (p.searchKey.includes(qtoks.join(" "))) return 3 * qtoks.length; // exact phrase
  const toks = nameTokens(p);
  let score = 0;
  for (const q of qtoks) {
    const tol = q.length >= 8 ? 2 : q.length >= 4 ? 1 : 0;
    let best = 0;
    for (const t of toks) {
      if (t.startsWith(q)) { best = 2; break; }
      if (tol && (editDistance(q, t.slice(0, q.length), tol) <= tol || editDistance(q, t, tol) <= tol)) best = Math.max(best, 1);
    }
    if (!best) return 0;
    score += best;
  }
  return score;
}
const queryTokens = () => fold(state.q).split(/[^a-z0-9]+/).filter(Boolean);

/* ---------- state <-> URL ---------- */
function readURL() {
  const p = new URLSearchParams(location.search);
  state.view = p.get("view") === "parts" ? "parts" : "people";
  state.q = p.get("q") || "";
  const ols = p.get("ols") || "";
  state.olsNone = ols === "none";
  // a link from before an olympiad was hidden simply loses that id (and the filter)
  state.ols = new Set((state.olsNone ? [] : ols.split(",").filter(Boolean)).filter(isVisibleOl));
  state.olsAll = p.get("modo") === "e";
  state.field = visibleValues("field").has(p.get("area")) ? p.get("area") : "";
  state.scope = visibleValues("scope").has(p.get("escopo")) ? p.get("escopo") : "";
  state.medal = p.get("medalha") || "";
  state.y0 = p.get("de") ? +p.get("de") : null;
  state.y1 = p.get("ate") ? +p.get("ate") : null;
  state.stats = p.get("cont") === "todas" ? "todas" : "filtradas";
  state.sort = state.view === "parts" ? { key: "year", dir: -1 } : { key: "participations", dir: -1 };
  const s = p.get("ord");
  if (s) {
    const [key, dir] = s.split(".");
    state.sort = { key, dir: dir === "asc" ? 1 : -1 };
  }
}
function writeURL() {
  const p = new URLSearchParams();
  if (state.view !== "people") p.set("view", state.view);
  if (state.q) p.set("q", state.q);
  if (state.olsNone) p.set("ols", "none");
  else if (state.ols.size) p.set("ols", [...state.ols].join(","));
  if (state.olsAll && state.ols.size > 1) p.set("modo", "e");
  if (state.field) p.set("area", state.field);
  if (state.scope) p.set("escopo", state.scope);
  if (state.medal) p.set("medalha", state.medal);
  if (state.y0) p.set("de", state.y0);
  if (state.y1) p.set("ate", state.y1);
  if (state.stats === "todas") p.set("cont", "todas");
  const def = state.view === "people" ? "participations" : "year";
  if (!(state.sort.key === def && state.sort.dir === -1))
    p.set("ord", `${state.sort.key}.${state.sort.dir === 1 ? "asc" : "desc"}`);
  const qs = p.toString();
  history.replaceState(null, "", qs ? `?${qs}` : location.pathname);
  try { sessionStorage.setItem("hof.filters", qs); } catch {}
}
/* Restore the last filter/sort state when the table is opened without a query string
   (e.g. coming back from a person page), so the list looks as it was left. */
function restoreSavedURL() {
  if (location.search) return;
  try {
    const saved = sessionStorage.getItem("hof.filters");
    if (saved) history.replaceState(null, "", `?${saved}`);
  } catch {}
}

/* ---------- filtering ---------- */
function partMatches(part) {
  const ol = OL.olympiads[part.olympiad];
  if (!ol || ol.hidden) return false;
  if (state.olsNone) return false;
  if (state.ols.size && !state.ols.has(part.olympiad)) return false;
  if (state.field && ol.field !== state.field) return false;
  if (state.scope && ol.scope !== state.scope) return false;
  if (state.y0 && part.year < state.y0) return false;
  if (state.y1 && part.year > state.y1) return false;
  if (state.medal) {
    if (state.medal === "none") {
      if (part.medal !== null || part.medalNote === "unknown" || part.medalNote === "pending") return false;
    } else if (part.medal !== state.medal) return false;
  }
  return true;
}
function coversAll(p) {
  if (!state.olsAll || state.ols.size < 2) return true;
  for (const ol of state.ols) if (!p.participations.some((x) => x.olympiad === ol && partMatches(x))) return false;
  return true;
}
function personRows() {
  const qt = queryTokens();
  const all = state.stats === "todas";
  return DATA.people
    .map((p) => [p, matchScore(p, qt)])
    .filter(([p, sc]) => sc > 0 && p.participations.some(partMatches) && coversAll(p))
    .map(([p, sc]) => {
      // Who is listed is decided by the filters; what the row counts follows "Contar": by default only
      // the participations that pass the filters, or — with 'todas' — the person's whole record.
      // Counts, badges, years and medals all describe the same set.
      const mine = all ? p.participations.filter((x) => isVisibleOl(x.olympiad)) : p.participations.filter(partMatches);
      const medals = { gold: 0, silver: 0, bronze: 0, "honorable-mention": 0 };
      let unknown = 0;
      for (const x of mine) {
        if (x.medal) medals[x.medal]++;
        else if (x.medalNote === "unknown") unknown++;
      }
      const years = mine.map((x) => x.year);
      const ols = [...new Set(mine.map((x) => x.olympiad))];
      // the olympiads left outside the counted set are still shown as badges, muted, so the row keeps
      // the full context without contradicting "Particip." / "Olimp. distintas" (empty when counting 'todas')
      const olsOut = all ? [] : [...new Set(p.participations.map((x) => x.olympiad))]
        .filter((o) => isVisibleOl(o) && !ols.includes(o));
      return {
        p,
        score: sc,
        name: p.name,
        participations: mine.length,
        ols,
        olsOut,
        distinct: ols.length,
        yearMin: Math.min(...years),
        yearMax: Math.max(...years),
        gold: medals.gold, silver: medals.silver, bronze: medals.bronze,
        hm: medals["honorable-mention"], unknown,
      };
    });
}
function partRows() {
  const qt = queryTokens();
  const rows = [];
  for (const p of DATA.people) {
    const sc = matchScore(p, qt);
    if (!sc || !coversAll(p)) continue;
    for (const x of p.participations)
      if (partMatches(x)) rows.push({ p, score: sc, name: p.name, year: x.year, olympiad: x.olympiad, medal: x.medal, medalNote: x.medalNote });
  }
  return rows;
}

/* ---------- sorting ---------- */
const CMP = {
  name: (a, b) => a.p.searchKey.localeCompare(b.p.searchKey),
  participations: (a, b) => a.participations - b.participations || a.gold - b.gold || a.silver - b.silver,
  distinct: (a, b) => a.distinct - b.distinct || a.participations - b.participations,
  // descending ("mais recentes") ranks by the latest year, ascending ("mais antigos") by the earliest
  years: (a, b) => (state.sort.dir === -1 ? a.yearMax - b.yearMax || a.yearMin - b.yearMin : a.yearMin - b.yearMin || a.yearMax - b.yearMax),
  gold: (a, b) => a.gold - b.gold || a.silver - b.silver || a.bronze - b.bronze,
  silver: (a, b) => a.silver - b.silver,
  bronze: (a, b) => a.bronze - b.bronze,
  hm: (a, b) => a.hm - b.hm,
  year: (a, b) => a.year - b.year,
  olympiad: (a, b) => a.olympiad.localeCompare(b.olympiad),
  medal: (a, b) => medalRank(a) - medalRank(b),
};
const medalRank = (r) => (r.medal ? MEDAL[r.medal].rank : r.medalNote === "unknown" ? 0.5 : 0);
function sortRows(rows) {
  const { key, dir } = state.sort;
  const cmp = CMP[key] || CMP.name;
  const byQuery = state.q.trim() ? (a, b) => b.score - a.score : () => 0; // best matches first while searching
  return rows.sort((a, b) => byQuery(a, b) || dir * cmp(a, b) || a.p.searchKey.localeCompare(b.p.searchKey));
}

/* ---------- rendering ---------- */
const COLS = {
  people: [
    ["name", "Nome"], ["participations", "Particip.", "num"], ["distinct", "Olimp. distintas", "num"],
    ["badges", "Olimpíadas"], ["years", "Anos"],
    ["gold", "Ouro", "num"], ["silver", "Prata", "num"], ["bronze", "Bronze", "num"], ["hm", "MH", "num"],
  ],
  parts: [["year", "Ano", "num"], ["olympiad", "Olimpíada"], ["name", "Nome"], ["medal", "Resultado"]],
};
function code(olId) {
  return `<span title="${OL.olympiads[olId].name}">${OL.olympiads[olId].code}</span>`;
}
/* an olympiad the row does not count (outside the filters): shown for context, dimmed */
function codeOut(olId) {
  return `<span class="out" title="${OL.olympiads[olId].name} — fora do filtro">${OL.olympiads[olId].code}</span>`;
}
function medalCell(r) {
  if (r.medal) return MEDAL[r.medal].label === "MH" ? "Menção honrosa" : MEDAL[r.medal].label;
  const n = NOTE[r.medalNote] || NOTE["no-award"];
  return n.text ? `<span class="muted" title="${n.label}">${n.text}</span>` : "";
}
function renderHead() {
  const cols = COLS[state.view];
  $("#thead").innerHTML =
    "<tr>" +
    cols.map(([key, label, cls]) => {
      const sortable = key !== "badges";
      const arrow = state.sort.key === (key === "years" && state.view === "people" ? "years" : key)
        ? ` <span class="arrow">${state.sort.dir === 1 ? "▲" : "▼"}</span>` : "";
      return `<th class="${cls || ""}" data-key="${sortable ? key : ""}">${label}${sortable ? arrow : ""}</th>`;
    }).join("") +
    "</tr>";
}
function renderBody(rows) {
  const tb = $("#tbody");
  if (state.view === "parts") {
    tb.innerHTML = rows.map((r) =>
      `<tr class="data" data-id="${r.p.id}"><td class="num c-year">${r.year}</td><td class="ols c-ol">${code(r.olympiad)}</td><td class="name"><a href="person.html?id=${r.p.id}">${r.name}</a></td><td class="c-medal">${medalCell(r)}</td></tr>`
    ).join("");
    return;
  }
  tb.innerHTML = rows.map((r) => {
    const yrs = r.yearMin === r.yearMax ? r.yearMin : `${r.yearMin}–${r.yearMax}`;
    return `<tr class="data" data-id="${r.p.id}">
      <td class="name"><a href="person.html?id=${r.p.id}">${r.name}</a></td>
      <td class="num c-parts">${r.participations}</td>
      <td class="num c-distinct">${r.distinct}</td>
      <td class="ols c-badges">${[...r.ols.map(code), ...r.olsOut.map(codeOut)].join(" ")}</td>
      <td class="c-years">${yrs}</td>
      <td class="num c-gold">${r.gold || ""}</td><td class="num c-silver">${r.silver || ""}</td>
      <td class="num c-bronze">${r.bronze || ""}</td><td class="num c-hm">${r.hm || ""}</td>
    </tr>`;
  }).join("");
}

let currentRows = [];
function render() {
  const rows = sortRows(state.view === "people" ? personRows() : partRows());
  currentRows = rows;
  renderHead();
  renderBody(rows);
  const n = rows.length;
  $("#empty").hidden = n > 0;
  $("#empty-text").textContent = state.view === "people"
    ? "Nenhum estudante encontrado com esses filtros."
    : "Nenhuma participação encontrada com esses filtros.";
  $("#result-line").innerHTML =
    state.view === "people"
      ? `${n} estudante${n === 1 ? "" : "s"}<span class="hint"> — clique em uma linha para abrir a página do estudante; clique nos cabeçalhos para ordenar</span>`
      : `${n} participaç${n === 1 ? "ão" : "ões"}`;
  syncSortSelect();
  writeURL();
}


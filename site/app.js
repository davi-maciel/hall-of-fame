  if (state.y0) $("#y0").value = state.y0;
  if (state.y1) $("#y1").value = state.y1;

  $("#q").addEventListener("input", (e) => { state.q = e.target.value; render(); });
  fsel.addEventListener("change", (e) => { state.field = e.target.value; render(); });
  ssel.addEventListener("change", (e) => { state.scope = e.target.value; render(); });
  $("#f-medal").addEventListener("change", (e) => { state.medal = e.target.value; render(); });
  $("#y0").addEventListener("change", (e) => { state.y0 = e.target.value ? +e.target.value : null; render(); });
